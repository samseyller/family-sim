// Build src/content/names.ts from SSA yearly name files and the 2010 Census surname list.
// Usage: node build-names.mjs <ssaDir> <censusCsv> <outFile>
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
const [ssaDir, censusCsv, out] = process.argv.slice(2);
const EXCLUDE = new Set(['Samuel', 'Sam']); // never use the project owner's name
const files = readdirSync(ssaDir).filter((f) => /^yob\d{4}\.txt$/.test(f));
const share = { F: new Map(), M: new Map() };
const raw = { F: new Map(), M: new Map() };
for (const f of files) {
  const rows = readFileSync(join(ssaDir, f), 'utf8').trim().split(/\r?\n/).map((l) => l.split(','));
  const tot = { F: 0, M: 0 };
  for (const [, sx, n] of rows) tot[sx] += Number(n);
  for (const [name, sx, n] of rows) {
    if (!/^[A-Za-z]+$/.test(name)) continue;
    share[sx].set(name, (share[sx].get(name) ?? 0) + Number(n) / tot[sx]);
    raw[sx].set(name, (raw[sx].get(name) ?? 0) + Number(n));
  }
}
function top(sx, k) {
  const other = sx === 'F' ? 'M' : 'F';
  return [...share[sx]].filter(([n]) => !EXCLUDE.has(n))
    .filter(([n]) => (raw[sx].get(n) ?? 0) / ((raw[sx].get(n) ?? 0) + (raw[other].get(n) ?? 0)) >= 0.8)
    .sort((a, b) => b[1] - a[1]).slice(0, k).map(([n]) => n);
}
const female = top('F', 500);
const male = top('M', 500);
const title = (s) => {
  const t = s.charAt(0) + s.slice(1).toLowerCase();
  return /^Mc[a-z]/.test(t) ? 'Mc' + t.charAt(2).toUpperCase() + t.slice(3) : t;
};
// The Census file drops apostrophes and spaces; restore the usual spellings.
const FIX = { Obrien: "O'Brien", Oconnor: "O'Connor", Oneill: "O'Neill", Oneal: "O'Neal", Odonnell: "O'Donnell", Oconnell: "O'Connell", Macdonald: 'MacDonald', Deleon: 'De Leon', Delacruz: 'De La Cruz', Dejesus: 'De Jesus', Delarosa: 'De La Rosa' };
const surnames = readFileSync(censusCsv, 'utf8').trim().split(/\r?\n/).slice(1)
  .map((l) => l.split(',')).filter((r) => /^[A-Z]+$/.test(r[0]) && Number(r[1]) > 0)
  .sort((a, b) => Number(a[1]) - Number(b[1])).slice(0, 1000).map((r) => FIX[title(r[0])] ?? title(r[0]));
const fmt = (arr) => arr.map((n) => (n.includes("'") ? `"${n}"` : `'${n}'`)).join(', ').replace(/(.{1,110})(, |$)/g, '  $1,\n').replace(/,,\n/g, ',\n');
const body = `/**
 * Common American names, generated by a one-off script from public-domain US government data:
 *  - first names: Social Security Administration baby-name data (national, one year per decade
 *    1950–2020, via github.com/hackerb9/ssa-baby-names). The 500 most common per sex by average share
 *    of births; a name is listed for a sex only if at least 80% of babies given it were that sex.
 *  - surnames: US Census Bureau, 2010 Census surnames (the 1,000 most common).
 */

export const FEMALE_NAMES = [
${fmt(female)}];

export const MALE_NAMES = [
${fmt(male)}];

export const LAST_NAMES = [
${fmt(surnames)}];
`;
writeFileSync(out, body);
console.log(`female ${female.length}, male ${male.length}, surnames ${surnames.length}`);
console.log('female sample', female.slice(0, 8).join(' '), '…', female.slice(-4).join(' '));
console.log('male sample', male.slice(0, 8).join(' '), '…', male.slice(-4).join(' '));
console.log('surname sample', surnames.slice(0, 8).join(' '), '…', surnames.slice(-4).join(' '), '| Mc:', surnames.filter((x) => x.startsWith('Mc')).slice(0, 4).join(' '));
